import type { Font } from 'opentype.js'
import { LABEL_CHARACTERS } from './label'
import { isElongated, trimNumber } from './outline'
import { DEFAULT_PRESET, SIZES_BY_SHAPE, type SizePreset } from './presets'
import { glyphOutlines } from './text'
import type { ShapeKind } from './types'

const SHAPE_NAMES: Record<ShapeKind, string> = { round: 'Round', oval: 'Oval', pill: 'Pill', rect: 'Rectangle', polygon: 'Hex' }
const GENERATED = /\/\/ <generated by scripts\/makerworld\.ts>\n[\s\S]*?\/\/ <\/generated>/
const STANDARD_SIZE = /^standard_size = .*$/m

const sizeKey = (preset: SizePreset) =>
  `${preset.shape}-${isElongated(preset.shape) ? `${trimNumber(preset.width)}x${trimNumber(preset.length ?? preset.width)}` : trimNumber(preset.width)}`

/** A Customizer dropdown splits options on commas and values from labels on colons. */
function option(value: string, label: string): string {
  if (/[,:\]]/.test(value + label)) throw new Error(`Customizer option cannot contain , : or ]: ${value}:${label}`)
  return `${value}:${label}`
}

function sizeOption(preset: SizePreset): string {
  const size = isElongated(preset.shape)
    ? `${trimNumber(preset.width)}×${trimNumber(preset.length ?? preset.width)}`
    : trimNumber(preset.width)
  return option(sizeKey(preset), `${SHAPE_NAMES[preset.shape]} ${size}mm - ${preset.use.replaceAll(', ', ' & ')}`)
}

const scadString = (text: string) => `"${text.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`
const units = (value: number) => String(Math.round(value * 1000) / 1000)

/** Ink bounds of each label character in font units, measured from the outlines the app extrudes. */
function glyphRows(font: Font): string[] {
  return [...LABEL_CHARACTERS].map((ch) => {
    const advance = units(font.charToGlyph(ch).advanceWidth ?? 0)
    const contours = glyphOutlines(font, ch, font.unitsPerEm)
    if (contours.length === 0) return `[${scadString(ch)}, ${advance}]`
    const xs = contours.flatMap((p) => p.map(([x]) => x))
    const ys = contours.flatMap((p) => p.map(([, y]) => y))
    const bounds = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)].map(units)
    return `[${scadString(ch)}, ${advance}, ${bounds.join(', ')}]`
  })
}

/**
 * The MakerWorld base script with its standard sizes and label glyph metrics
 * regenerated from the app's presets and bundled font, so the two cannot drift.
 */
export function makerworldBaseSource(font: Font, source: string): string {
  const presets = Object.values(SIZES_BY_SHAPE).flat()
  const sizes = presets.map((p) => `  [${scadString(sizeKey(p))}, ${scadString(p.shape)}, ${p.width}, ${p.length ?? p.width}],`)
  const generated = [
    '// <generated by scripts/makerworld.ts>',
    `UNITS_PER_EM = ${font.unitsPerEm};`,
    '// [key, shape, width, length]',
    'SIZES = [',
    ...sizes,
    '];',
    '// [character, advance, xMin, xMax, yMin, yMax] in font units; blank glyphs carry only their advance.',
    'GLYPHS = [',
    ...glyphRows(font).map((row) => `  ${row},`),
    '];',
    '// </generated>',
  ].join('\n')
  const dropdown = [option('custom', 'Custom'), ...presets.map(sizeOption)].join(', ')
  if (!GENERATED.test(source) || !STANDARD_SIZE.test(source)) throw new Error('makerworld/base.scad is missing its generated markers')
  return source
    .replace(STANDARD_SIZE, () => `standard_size = ${scadString(sizeKey(DEFAULT_PRESET))}; // [${dropdown}]`)
    .replace(GENERATED, () => generated)
}
