import type { Font } from 'opentype.js'
import { LABEL_CHARACTERS } from './label'
import { isElongated, trimNumber } from './outline'
import { SIZES_BY_SHAPE, type SizePreset } from './presets'
import { glyphOutlines } from './text'
import type { ShapeKind } from './types'

const SHAPE_NAMES: Record<ShapeKind, string> = { round: 'Round', oval: 'Oval', pill: 'Pill', rect: 'Rectangle', polygon: 'Hex' }
const GENERATED = /\/\/ <generated by scripts\/makerworld\.ts:([^>]*)>\n[\s\S]*?\/\/ <\/generated>/
const STANDARD_SIZE = /^standard_size = "([^"]*)";.*$/m

const sizeKey = (preset: SizePreset) =>
  `${preset.shape}-${isElongated(preset.shape) ? `${trimNumber(preset.width)}x${trimNumber(preset.length ?? preset.width)}` : trimNumber(preset.width)}`

/** A Customizer dropdown splits options on commas and values from labels on colons. */
function option(value: string, label: string): string {
  if (/[,:\]]/.test(value + label)) throw new Error(`Customizer option cannot contain , : or ]: ${value}:${label}`)
  return `${value}:${label}`
}

function sizeOption(preset: SizePreset): string {
  const size = isElongated(preset.shape)
    ? `${trimNumber(preset.width)}×${trimNumber(preset.length ?? preset.width)}`
    : trimNumber(preset.width)
  return option(sizeKey(preset), `${SHAPE_NAMES[preset.shape]} ${size}mm - ${preset.use.replaceAll(', ', ' & ')}`)
}

const scadString = (text: string) => `"${text.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`
const units = (value: number) => String(Math.round(value * 1000) / 1000)

/** Ink bounds of each label character in font units, measured from the outlines the app extrudes. */
function glyphRows(font: Font): string[] {
  return [...LABEL_CHARACTERS].map((ch) => {
    const advance = units(font.charToGlyph(ch).advanceWidth ?? 0)
    const contours = glyphOutlines(font, ch, font.unitsPerEm)
    if (contours.length === 0) return `[${scadString(ch)}, ${advance}]`
    const xs = contours.flatMap((p) => p.map(([x]) => x))
    const ys = contours.flatMap((p) => p.map(([, y]) => y))
    const bounds = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)].map(units)
    return `[${scadString(ch)}, ${advance}, ${bounds.join(', ')}]`
  })
}

const fine = (value: number) => String(Math.round(value * 100) / 100)

/**
 * Glyph contours exactly as the app extrudes them, for the characters after
 * `outlines:` or every label character. OpenSCAD's `text()` hints glyphs and
 * moves their points by tenths of a font unit, which misses parity wherever
 * text is most of a part.
 */
function outlineRows(font: Font, table: string): string[] {
  const characters = table.includes(':') ? table.slice(table.indexOf(':') + 1) : LABEL_CHARACTERS
  for (const ch of characters) if (!LABEL_CHARACTERS.includes(ch)) throw new Error(`Unknown outline character: ${ch}`)
  return [...characters].map((ch) => {
    const contours = glyphOutlines(font, ch, font.unitsPerEm).map((c) => `[${c.map(([x, y]) => `[${fine(x)},${fine(y)}]`).join(',')}]`)
    return `[${scadString(ch)}, [${contours.join(', ')}]]`
  })
}

/** Standard sizes of the shapes named after `sizes:` in the marker, or every shape for a bare `sizes`. */
function presetsFor(table: string): SizePreset[] {
  const shapes = table.split(':')[1]?.split(',') as ShapeKind[] | undefined
  for (const shape of shapes ?? []) if (!(shape in SIZES_BY_SHAPE)) throw new Error(`Unknown shape in generated marker: ${shape}`)
  return (shapes ?? (Object.keys(SIZES_BY_SHAPE) as ShapeKind[])).flatMap((shape) => SIZES_BY_SHAPE[shape])
}

/**
 * A MakerWorld script with its generated tables rebuilt from the app's presets
 * and bundled font, so the two cannot drift. The marker line names the tables:
 * `// <generated by scripts/makerworld.ts: sizes glyphs>` emits `SIZES` and
 * `UNITS_PER_EM` with `GLYPHS`, `sizes:round,rect` limits the shapes, and
 * `outlines` or `outlines:0123456789` emits `OUTLINES`. A
 * `standard_size` line, when present, gets the same sizes as dropdown options
 * and keeps its default.
 */
export function makerworldSource(font: Font, source: string): string {
  const marker = GENERATED.exec(source)
  if (!marker) throw new Error('script is missing its generated markers')
  const tables = marker[1].trim().split(/\s+/).filter(Boolean)
  const lines = [`// <generated by scripts/makerworld.ts: ${tables.join(' ')}>`]
  let presets: SizePreset[] = []
  for (const table of tables) {
    if (table === 'glyphs') {
      lines.push(
        `UNITS_PER_EM = ${font.unitsPerEm};`,
        '// [character, advance, xMin, xMax, yMin, yMax] in font units; blank glyphs carry only their advance.',
        'GLYPHS = [',
        ...glyphRows(font).map((row) => `  ${row},`),
        '];',
      )
    } else if (table === 'outlines' || table.startsWith('outlines:')) {
      lines.push(
        "// [character, [contour, ...]]: flattened like the app's glyphOutlines, in font units, y up. Fill non-zero.",
        'OUTLINES = [',
        ...outlineRows(font, table).map((row) => `  ${row},`),
        '];',
      )
    } else if (table === 'sizes' || table.startsWith('sizes:')) {
      presets = presetsFor(table)
      lines.push(
        '// [key, shape, width, length]',
        'SIZES = [',
        ...presets.map((p) => `  [${scadString(sizeKey(p))}, ${scadString(p.shape)}, ${p.width}, ${p.length ?? p.width}],`),
        '];',
      )
    } else {
      throw new Error(`Unknown generated table: ${table}`)
    }
  }
  lines.push('// </generated>')
  let result = source.replace(GENERATED, () => lines.join('\n'))
  const standard = STANDARD_SIZE.exec(result)
  if (standard) {
    if (presets.length === 0) throw new Error('standard_size needs a sizes table')
    const keys = presets.map(sizeKey)
    if (standard[1] !== 'custom' && !keys.includes(standard[1])) throw new Error(`standard_size default is not a size: ${standard[1]}`)
    const dropdown = [option('custom', 'Custom'), ...presets.map(sizeOption)].join(', ')
    result = result.replace(STANDARD_SIZE, () => `standard_size = ${scadString(standard[1])}; // [${dropdown}]`)
  }
  return result
}
