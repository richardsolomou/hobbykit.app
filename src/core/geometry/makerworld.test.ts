import { readdirSync, readFileSync } from 'node:fs'
import { parse } from 'opentype.js'
import { describe, expect, it } from 'vitest'
import { makerworldSource } from './makerworld'

const bytes = readFileSync('src/assets/fonts/oswald-700.woff')
const font = parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength))
const scripts = readdirSync('makerworld').filter((name) => name.endsWith('.scad'))

describe.each(scripts)('makerworld/%s', (name) => {
  it('carries the current generated tables; run `just makerworld` if not', () => {
    const source = readFileSync(`makerworld/${name}`, 'utf8')
    expect(makerworldSource(font, source)).toBe(source)
  })
})

describe('makerworldSource', () => {
  const block = (tables: string) => `// <generated by scripts/makerworld.ts: ${tables}>\n// </generated>\n`

  it('refuses a script that has lost its generated block', () => {
    expect(() => makerworldSource(font, 'standard_size = "round-32";\n')).toThrow(/generated markers/)
  })

  it('limits sizes to the shapes the marker names', () => {
    expect(makerworldSource(font, block('sizes:rect'))).not.toContain('"round-32"')
  })

  it('refuses a standard size default that is not offered', () => {
    expect(() => makerworldSource(font, `standard_size = "oval-60x35.5";\n${block('sizes:round')}`)).toThrow(/not a size/)
  })

  it('emits outlines only for the characters the marker names', () => {
    const source = makerworldSource(font, block('outlines:7'))
    expect(source.match(/^ {2}\["/gm)).toHaveLength(1)
  })
})
